CREATE SCHEMA IF NOT EXISTS context;

CREATE TABLE context.skills (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id INT NOT NULL REFERENCES iam.teams(id) ON DELETE CASCADE,
    name VARCHAR NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    visibility visibility NOT NULL,
    created_by INT NOT NULL REFERENCES iam.users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE context.skill_files (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id INT NOT NULL REFERENCES context.skills(id) ON DELETE CASCADE,
    object_id INT NOT NULL REFERENCES storage.objects(id) ON DELETE CASCADE,
    relative_path TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(skill_id, relative_path)
);

SELECT updated_at('context.skills');

