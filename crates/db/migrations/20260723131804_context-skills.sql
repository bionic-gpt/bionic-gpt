GRANT USAGE ON SCHEMA context TO application_readonly;
GRANT SELECT, INSERT, UPDATE, DELETE ON context.skills, context.skill_files TO application_user;
GRANT USAGE, SELECT ON context.skills_id_seq, context.skill_files_id_seq TO application_user;
GRANT SELECT ON context.skills, context.skill_files TO application_readonly;
GRANT SELECT ON context.skills_id_seq, context.skill_files_id_seq TO application_readonly;

