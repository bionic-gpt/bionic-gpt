-- Remove conversations which belonged to assistants before deleting their prompts.
DELETE FROM llm.conversations
WHERE id IN (
    SELECT DISTINCT c.conversation_id
    FROM llm.chats c
    JOIN assistants.prompts p ON p.id = c.prompt_id
    WHERE p.prompt_type = 'Assistant'
);

DELETE FROM storage.objects
WHERE id IN (
    SELECT image_icon_object_id
    FROM assistants.prompts
    WHERE prompt_type = 'Assistant'
      AND image_icon_object_id IS NOT NULL
);

DELETE FROM assistants.prompts WHERE prompt_type = 'Assistant';

