CREATE TYPE prompt_type AS ENUM ('Assistant', 'Model');

ALTER TABLE assistants.prompts
    ADD COLUMN prompt_type prompt_type NOT NULL DEFAULT 'Model',
    ADD COLUMN category_id INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN image_icon_object_id INTEGER,
    ADD COLUMN max_chunks INTEGER NOT NULL DEFAULT 10;

CREATE TABLE assistants.categories (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    description TEXT
);

GRANT SELECT, INSERT, UPDATE, DELETE ON assistants.categories TO application_user;
