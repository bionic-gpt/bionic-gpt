CREATE TABLE integrations.mcp_servers (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id INT NOT NULL REFERENCES iam.teams(id) ON DELETE CASCADE,
    return_team_id TEXT NOT NULL,
    created_by INT NOT NULL REFERENCES iam.users(id) ON DELETE CASCADE,
    visibility visibility NOT NULL,
    name TEXT NOT NULL,
    server_url TEXT NOT NULL,
    auth_type TEXT NOT NULL DEFAULT 'none' CHECK (auth_type IN ('none', 'bearer', 'oauth2')),
    access_token TEXT,
    refresh_token TEXT,
    authorization_url TEXT,
    token_url TEXT,
    oauth_scopes TEXT,
    client_id TEXT,
    client_secret TEXT,
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (
        (auth_type = 'none' AND access_token IS NULL)
        OR (auth_type = 'bearer' AND access_token IS NOT NULL)
        OR (auth_type = 'oauth2' AND authorization_url IS NOT NULL AND token_url IS NOT NULL AND client_id IS NOT NULL)
    ),
    CHECK (server_url ~ '^https?://')
);

CREATE INDEX mcp_servers_team_idx ON integrations.mcp_servers(team_id, visibility);
